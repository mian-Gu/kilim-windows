"""Generate the Rust include table for split rug assets; alpha-edge quantization is bounded."""
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
directory = root / "windows/assets/patterns"
entries = json.loads((directory / "index.json").read_text(encoding="utf-8"))
assert len(entries) == 15
rows = ["// Generated by scripts/pack-rug-assets.py. Geometry: upstream RugTexture.swift.",
        "pub const PRESETS: &[Preset] = &["]
manifest = {"source_sha256": hashlib.sha256((root / "Sources/Kilim/Rendering/RugTexture.swift").read_bytes()).hexdigest(), "width":1536, "height":1032, "patterns":[]}
for entry in entries:
    theme, seed = entry["theme"], int(entry["seed"])
    assert theme.isalpha()
    rows.append(f'    Preset {{ key: "{theme}", base: include_bytes!("patterns/{theme}.base.png"), fringe: include_bytes!("patterns/{theme}.fringe.png"), seed: {seed} }},')
    manifest["patterns"].append({"theme":theme,"seed":str(seed),"base_sha256":hashlib.sha256((directory/f"{theme}.base.png").read_bytes()).hexdigest(),"fringe_sha256":hashlib.sha256((directory/f"{theme}.fringe.png").read_bytes()).hexdigest()})
rows.append("];")
(root / "windows/assets/patterns.rs").write_text("\n".join(rows) + "\n", encoding="utf-8")
(root / "windows/assets/patterns-manifest.json").write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")
print("Packed pattern bytes:", sum(path.stat().st_size for path in directory.glob("*.png")))
